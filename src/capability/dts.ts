import { CapabilityRecord } from './store.js';

/**
 * The capability catalog as a TypeScript declaration.
 *
 * A `ts-program` plan is written against this: the agent gets column names,
 * types and the written semantics as doc comments, so it can compose a query
 * without a round trip to ask what a table looks like. It is generated rather
 * than hand-maintained because the catalog changes whenever a source does.
 */

function ident(s: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(s) ? s : JSON.stringify(s);
}

function comment(cap: CapabilityRecord, indent: string): string {
  const lines: string[] = [];
  if (cap.title) lines.push(cap.title);
  const semantics = cap.semantics.trim();
  if (semantics && semantics !== cap.title) lines.push(...semantics.split('\n').slice(0, 12));
  if (cap.freshnessSeconds !== null) lines.push(`freshness: answers may be up to ${cap.freshnessSeconds}s old`);
  if (cap.cost !== 1) lines.push(`cost: ${cap.cost} (relative)`);
  for (const p of cap.pitfalls) lines.push(`pitfall: ${p}`);
  for (const j of cap.joins) lines.push(`join: ${j}`);
  for (const q of cap.sampleQueries.slice(0, 3)) lines.push(`example: ${q}`);
  if (lines.length === 0) return '';
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`).join('\n')}\n${indent} */\n`;
}

function columnsOf(cap: CapabilityRecord): { name: string; type: string }[] {
  const schema = cap.schema as { columns?: { name: string; type: string }[] } | undefined;
  return Array.isArray(schema?.columns) ? schema!.columns! : [];
}

/** Map a source's own type name onto something a TS reader recognizes. */
function tsType(raw: string): string {
  const t = raw.toLowerCase();
  if (/int|float|double|decimal|numeric|real|bigint/.test(t)) return 'number';
  if (/bool/.test(t)) return 'boolean';
  if (/date|time/.test(t)) return 'string /* timestamp */';
  return 'string';
}

export function renderCapabilityDts(capabilities: CapabilityRecord[]): string {
  const bySource = new Map<string, CapabilityRecord[]>();
  for (const c of capabilities) {
    (bySource.get(c.sourceId) ?? bySource.set(c.sourceId, []).get(c.sourceId)!).push(c);
  }

  const out: string[] = [
    '// Generated by knode-os — the capabilities this knowledge base can reach.',
    '// Statements are written in each source\'s own dialect; see `dialect` per capability.',
    '',
    'export interface QueryResult<Row = Record<string, unknown>> {',
    '  source: string;',
    '  columns: string[];',
    '  rows: Row[];',
    '  rowCount: number;',
    '  truncated: boolean;',
    '  /** When the rows were read from the live system. */',
    '  asOf: string;',
    '  elapsedMs: number;',
    '}',
    '',
    'export interface QueryOptions {',
    '  maxRows?: number;',
    '  timeoutMs?: number;',
    '}',
    '',
    'export declare const live: {',
  ];

  for (const [sourceId, caps] of [...bySource.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    out.push(`  ${ident(sourceId)}: {`);
    for (const cap of caps.sort((a, b) => a.name.localeCompare(b.name))) {
      const cols = columnsOf(cap);
      const row = cols.length > 0
        ? `{ ${cols.map((c) => `${ident(c.name)}: ${tsType(c.type)}`).join('; ')} }`
        : 'Record<string, unknown>';
      out.push(comment(cap, '    ').trimEnd());
      out.push(`    ${ident(cap.name)}: {`);
      out.push(`      readonly dialect: ${JSON.stringify(cap.dialect)};`);
      out.push(`      query(statement: string, opts?: QueryOptions): Promise<QueryResult<${row}>>;`);
      out.push('    };');
    }
    out.push('  };');
  }
  out.push('};', '');
  return out.filter((l) => l !== '').join('\n') + '\n';
}
