import path from 'node:path';
import { PGlite } from '@electric-sql/pglite';
import { vector } from '@electric-sql/pglite-pgvector';
import { DB_DIR } from '../fs/datadir.js';

/**
 * PGlite-backed store. The database is a derived index over the markdown/file
 * tree — deleting <data>/.knode and re-running `knode-os ingest` rebuilds it.
 */

const SCHEMA = `
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS meta (
  key   TEXT PRIMARY KEY,
  value JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS documents (
  id         TEXT PRIMARY KEY,
  path       TEXT NOT NULL UNIQUE,
  root       TEXT NOT NULL,
  title      TEXT,
  sha256     TEXT NOT NULL,
  mime       TEXT,
  bytes      INTEGER NOT NULL DEFAULT 0,
  status     TEXT NOT NULL DEFAULT 'pending',
  error      TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chunks (
  id          TEXT PRIMARY KEY,
  document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  seq         INTEGER NOT NULL,
  content     TEXT NOT NULL,
  token_count INTEGER NOT NULL DEFAULT 0,
  metadata    JSONB NOT NULL DEFAULT '{}',
  tsv         tsvector,
  UNIQUE (document_id, seq)
);
CREATE INDEX IF NOT EXISTS chunks_tsv_idx ON chunks USING GIN (tsv);
CREATE INDEX IF NOT EXISTS chunks_doc_idx ON chunks (document_id);

CREATE TABLE IF NOT EXISTS entities (
  id            TEXT PRIMARY KEY,
  name          TEXT NOT NULL,
  type          TEXT NOT NULL DEFAULT 'concept',
  description   TEXT NOT NULL DEFAULT '',
  aliases       JSONB NOT NULL DEFAULT '[]',
  wiki_path     TEXT,
  mention_count INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS relations (
  id          TEXT PRIMARY KEY,
  source_id   TEXT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
  target_id   TEXT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
  type        TEXT NOT NULL DEFAULT 'related_to',
  description TEXT NOT NULL DEFAULT '',
  weight      REAL NOT NULL DEFAULT 1.0,
  document_id TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS relations_source_idx ON relations (source_id);
CREATE INDEX IF NOT EXISTS relations_target_idx ON relations (target_id);

CREATE TABLE IF NOT EXISTS entity_mentions (
  entity_id   TEXT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
  chunk_id    TEXT NOT NULL REFERENCES chunks(id) ON DELETE CASCADE,
  document_id TEXT NOT NULL,
  PRIMARY KEY (entity_id, chunk_id)
);
CREATE INDEX IF NOT EXISTS mentions_chunk_idx ON entity_mentions (chunk_id);

CREATE TABLE IF NOT EXISTS traces (
  id          TEXT PRIMARY KEY,
  source      TEXT NOT NULL,
  session_id  TEXT,
  path        TEXT NOT NULL UNIQUE,
  project     TEXT,
  started_at  TIMESTAMPTZ,
  bytes       INTEGER NOT NULL DEFAULT 0,
  sha256      TEXT NOT NULL DEFAULT '',
  analyzed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS suggestions (
  id          TEXT PRIMARY KEY,
  kind        TEXT NOT NULL,
  title       TEXT NOT NULL,
  body        TEXT NOT NULL,
  evidence    JSONB NOT NULL DEFAULT '[]',
  status      TEXT NOT NULL DEFAULT 'pending',
  report_path TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
`;

export class Store {
  private constructor(
    public readonly db: PGlite,
    public readonly dataDir: string,
    public readonly embeddingDim: number,
  ) {}

  /**
   * Open (or create) the store. The embeddings table is created with the
   * configured dimension; if the dimension changed since last run the table is
   * rebuilt (embeddings must then be regenerated by `ingest`).
   */
  static async open(dataDir: string, embeddingDim: number): Promise<Store> {
    const db = await PGlite.create(path.join(dataDir, DB_DIR), { extensions: { vector } });
    await db.exec(SCHEMA);

    const prev = await db.query<{ value: { dim: number; } }>(`SELECT value FROM meta WHERE key = 'embedding'`);
    const prevDim = prev.rows[0]?.value?.dim;
    if (prevDim !== undefined && prevDim !== embeddingDim) {
      await db.exec(`DROP TABLE IF EXISTS embeddings;`);
      await db.exec(`UPDATE documents SET status = 'pending';`);
      console.warn(`[knode-os] embedding dimension changed ${prevDim} -> ${embeddingDim}; embeddings dropped, re-run ingest.`);
    }
    await db.exec(`
      CREATE TABLE IF NOT EXISTS embeddings (
        chunk_id  TEXT PRIMARY KEY REFERENCES chunks(id) ON DELETE CASCADE,
        model     TEXT NOT NULL,
        embedding vector(${embeddingDim}) NOT NULL
      );
    `);
    await db.query(
      `INSERT INTO meta (key, value) VALUES ('embedding', $1::jsonb)
       ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`,
      [JSON.stringify({ dim: embeddingDim })],
    );
    return new Store(db, dataDir, embeddingDim);
  }

  async query<T>(sql: string, params?: unknown[]): Promise<T[]> {
    const res = await this.db.query<T>(sql, params);
    return res.rows;
  }

  async exec(sql: string): Promise<void> {
    await this.db.exec(sql);
  }

  async getMeta<T>(key: string): Promise<T | undefined> {
    const rows = await this.query<{ value: T }>(`SELECT value FROM meta WHERE key = $1`, [key]);
    return rows[0]?.value;
  }

  async setMeta(key: string, value: unknown): Promise<void> {
    await this.query(
      `INSERT INTO meta (key, value) VALUES ($1, $2::jsonb)
       ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`,
      [key, JSON.stringify(value)],
    );
  }

  async close(): Promise<void> {
    await this.db.close();
  }
}

/** Serialize a JS number[] for a pgvector parameter. */
export function toVectorLiteral(v: number[]): string {
  return `[${v.map((x) => (Number.isFinite(x) ? +x.toFixed(7) : 0)).join(',')}]`;
}
